// 食物繊維・ビタミンD・カルシウム・純アルコール・食塩相当量の基準値と、
// 純アルコール量(g)への変換を扱う純粋関数群。
//
// 【このモジュールが存在する理由】
// このアプリはこれまでカロリー・タンパク質(死守2項目)、脂質・炭水化物(二次表示)を
// 扱ってきたが、いずれも「この人に何が不足しやすいか」という観点では選ばれていなかった。
// 以下の5項目は、日本人・成人男性・1〜2食(夕食+朝のプロテインのみ)・週3回の
// マシントレーニング+週2時間のバドミントン・ほぼ毎日飲酒、という属性に対して
// 具体的に不足/超過しやすいと判断したものだけを選んでいる。
//
// 【なぜこの5つで、他(亜鉛・マグネシウム・ビタミンB群・鉄・オメガ3)を足さないか】
// ACSM 2016はアスリートで注意すべき微量栄養素としてカルシウム・ビタミンD・鉄・一部の
// 抗酸化物質を挙げているが、鉄は月経・フットストライク溶血・高地順化のいずれも
// 当てはまらない成人男性では欠乏リスクが低く、このユーザーの推定摂取量は約10.5mg
// (RDA 7.0〜7.5mgに対して十分)であるため対象外にした。亜鉛・マグネシウム・
// ビタミンB群・オメガ3もこの人固有の欠乏根拠が無い。誰も入力しないフィールドを
// 増やすことは、このアプリ全体の「立って使う・軽いトラッカー」という前提を損なう
// (ブリーフ原文: 「a tracker nobody fills in is worse than no tracker」)。
//
// 【なぜ食物繊維】日本人成人の食物繊維摂取量の中央値は13.3g/日で、目標量20〜22g/日を
// 大きく下回る。Reynolds et al. 2019 (The Lancet, メタ解析)は25〜29g/日でリスク低減が
// 最大になるとしており、1〜2食しか食べないこのユーザーの食べ方は構造的に不足しやすい。
//
// 【なぜビタミンD】日本人成人のビタミンD不足/欠乏は夏でも47.7%、冬は82.2%に達するという
// 報告がある。ACSM 2016は北緯35度以北のアスリート・屋内トレーニング中心のアスリートに
// 特に注意を促しており、このユーザーは両方に該当する(日本・マシン中心の屋内トレーニング)。
//
// 【なぜカルシウム】日本人はカルシウムが慢性的に不足している集団であり、2025年版の
// 食事摂取基準は骨粗鬆症をカルシウム・ビタミンD・タンパク質の対象疾患として新たに
// 明記した。骨は男性のRED-Sの主要な帰結でもあり、既存のEAフロア(js/energy.js)と
// 対になる指標として扱う。
//
// 【なぜ純アルコールをgで】「量(ml) × 度数(%) ÷ 100 × 0.8」が全ての飲酒ガイドラインの
// 共通単位であり、mlのままでは「発泡酒500ml」と「ビール500ml」の実際のリスクの違いが
// 数字に出てこない。MHLW 2024の目安は生活習慣病のリスクを高める量が男性40g/日。
// このユーザーの日課(500ml・5%)は20gで、40gの半分。これは「危険」ではなく
// 比較のための目安として見せるべき数字であり、本モジュールはそのための変換だけを
// 提供する(危険性の判定や表示文言は呼び出し側の責務)。
//
// 【アルコールのkcalの扱い・確定した方針】
// 以前ここには「1日のカロリー予算のうち最も手軽に取り戻せる約220kcal」と書かれていた。
// つまり削れる余剰という位置づけである。一方 js/nutrition.js の dayTotals は
// アルコールのkcalを totals.kcal に含め、achievement() はその値をEAフロアと比較していた
// = 安全下限を満たすエネルギーとして数えていた。同一コードベースが2つの立場を
// 同時に取っており、どちらの方針で実装すればよいか誰も決められない状態だった。
//
// 確定: 【アルコールのkcalはEAの分子に算入する】
// 理由は、EA(エネルギー可用性)が「総摂取エネルギー」で定義されているため
// (Mountjoy et al. ACSM/AND/DC 2016)。除外すると、文献の 30 / 45 kcal/kgFFM/日 という
// 基準値と比較できない独自の数字になり、閾値の根拠そのものが失われる。
// 「削れる余剰」という表現はここから削除する。
// ただしアルコール由来のエネルギーが筋タンパク質の合成に使われないことは事実なので、
// 記録タブのEAカードで内訳(何kcal・全体の何%)を明示する
// (js/recordTab.js の renderEnergyCard)。警告としては出さない。
// 毎日飲む習慣に対して割合で警告を出せば毎日必ず点灯し、
// js/nutrition.js の dayOver 誤爆と同じ「無視される警告」になるため。
//
// 【なぜ食塩相当量】日本人の食生活の文脈で目標量(7.5g未満、重症化予防6.0g)が明確にあり、
// この人の食生活(唐揚げ・味噌汁・おにぎり等の和食中心)では超過しやすい。protein/kcalと
// 違い、これは「上限を守る」ためのceiling指標として扱う(下回るほど良い)。
//
// 出典まとめ: 日本人の食事摂取基準(2025年版) / MHLW「飲酒ガイドライン」(2024) /
// Reynolds et al. 2019 (Lancet 393:434-445) / ACSM/AND/DC 2016 (Med Sci Sports Exerc 48(3):543-568)

/**
 * 年代区分。日本人の食事摂取基準(2025年版)は成人を細かい年代帯に分けており、
 * このブリーフが扱う5項目のうち食物繊維(20g/22g)とカルシウム(800mg/750mg)の
 * 2項目が「18-29歳」と「30-49歳」で異なる値を持つ。
 *
 * 【正直な注記】このモジュールの設計のもとになった研究ブリーフには「5項目のうち
 * 3項目が年代で異なる」という記述があったが、ブリーフ自身が示した数値表では
 * ビタミンD(9.0µg、両区分共通)と食塩相当量(7.5g未満、両区分共通)は年代で
 * 変わっておらず、実際に年代で異なるのは食物繊維とカルシウムの2項目だけである。
 * 存在しない3項目目の差分を捏造してつじつまを合わせることはせず、数値表の通り
 * 2項目のみを年代依存として実装した。この食い違いはブリーフ側の記述ミスの
 * 可能性が高いと考えている。
 */
export const AGE_BANDS = { YOUNG: '18-29', MID: '30-49' };

/**
 * profile.age から年代区分を返す。18〜29歳は YOUNG、それ以外(30歳以上、および
 * 不正/未入力値)は MID にフォールバックする。このアプリは単一の成人男性ユーザー用で
 * 50歳以上の区分は食事摂取基準には別途あるが、対象ユーザーが該当しないため実装しない
 * (必要になった時点で追加すればよく、今は使われない区分を先回りして増やさない)。
 */
export function ageBand(age) {
  const a = Number(age);
  if (Number.isFinite(a) && a >= 18 && a <= 29) return AGE_BANDS.YOUNG;
  return AGE_BANDS.MID;
}

// 食物繊維(目標量)・カルシウム(推奨量、耐容上限量2,500mg/日は年代共通) — 日本人の食事摂取基準2025年版
const BAND_VALUES = {
  [AGE_BANDS.YOUNG]: { fibreG: 20, calciumMg: 800 },
  [AGE_BANDS.MID]: { fibreG: 22, calciumMg: 750 }
};

export const VITAMIN_D_UG = 9.0;      // 目安量(全年代共通) — 日本人の食事摂取基準2025年版
export const VITAMIN_D_UL_UG = 100;   // 耐容上限量 — 同上
export const CALCIUM_UL_MG = 2500;    // 耐容上限量(全年代共通) — 同上
export const SALT_TARGET_G = 7.5;     // 目標量(男性、< 7.5g/日) — 同上
export const SALT_SEVERE_PREVENTION_G = 6.0; // 重症化予防を意識する場合の目安 — 同上
export const ALCOHOL_RISK_G = 40;     // 生活習慣病のリスクを高める量(男性) — MHLW飲酒ガイドライン2024

/**
 * profile.age から5項目分の基準値をまとめて返す。band を含めるのは、呼び出し側の
 * 画面表示で「あなたは30-49歳の基準を使っています」と根拠を示せるようにするため
 * (js/recordTab.js のEAカード等、このアプリは一貫して数式・根拠を隠さない方針)。
 */
export function microTargetsForAge(age) {
  const band = ageBand(age);
  const { fibreG, calciumMg } = BAND_VALUES[band];
  return {
    band,
    fibreG,
    calciumMg,
    calciumUlMg: CALCIUM_UL_MG,
    vitaminDUg: VITAMIN_D_UG,
    vitaminDUlUg: VITAMIN_D_UL_UG,
    saltG: SALT_TARGET_G,
    saltSevereG: SALT_SEVERE_PREVENTION_G,
    alcoholRiskG: ALCOHOL_RISK_G
  };
}

// 【製品仕様】このユーザーが実際に飲んでいる発泡酒の度数(500mlの缶・5%)。
// 研究由来の値ではなく、商品ラベルに書かれている数字そのもの。
// このユーザーの実際の飲酒習慣(500mlの缶、5%)に基づく既定の度数。食品マスタ
// (data/foods.json)やOCR結果が度数を持たない場合のフォールバックとしてのみ使う。
// ウイスキーの水割り等、度数が大きく異なる飲料を扱う必要が生じたら、食品側に
// alcoholAbvPct を明示すればこの既定値は使われなくなる。
export const DEFAULT_ALCOHOL_ABV_PCT = 5;

/**
 * 純アルコール量(g) = 量(ml) × 度数(%) ÷ 100 × 0.8。
 * 出典: MHLW「飲酒ガイドライン」(2024)。500ml・5%なら 500×0.05×0.8 = 20g。
 * ml/度数のいずれかが不正(非数値・0以下)なら0を返す(dayTotalsの他の集計と同じく、
 * 壊れた入力で例外を投げて集計全体を止めない)。
 */
export function alcoholGrams(ml, abvPct = DEFAULT_ALCOHOL_ABV_PCT) {
  const v = Number(ml);
  const abv = Number(abvPct);
  if (!Number.isFinite(v) || v <= 0 || !Number.isFinite(abv) || abv <= 0) return 0;
  return v * (abv / 100) * 0.8;
}

// --- ALDH2(アルコール分解酵素)フラッシング質問 ---
//
// 「お酒を飲むと顔が赤くなりますか？」は一度だけ尋ね(profile.aldh2Flushing)、
// 設定タブ(js/settingsTab.js)からいつでも再回答できる。食事タブ(js/mealTab.js)は
// この回答に応じた注記の表示/非表示を判断する。この関数は両方の呼び出し元から
// 共有される、回答保存時の状態遷移だけを表す純粋関数(profileは呼び出し側が
// store.set するので、ここではオブジェクトを返すだけで永続化はしない)。
export const ALDH2_ANSWERS = ['yes', 'no', 'skipped'];

/**
 * 回答を保存した後のprofileを返す。'yes'に新たに変わった場合(以前は違う回答だった
 * 場合)だけ、一度閉じた注記を再び見せる(aldh2NoticeDismissedをfalseに戻す)。
 * 既に'yes'のまま据え置き保存された場合は、閉じた通知をまた出さない
 * (ブリーフの要求通り、毎日/毎回は繰り返さない)。
 */
export function applyAldh2Answer(profile, answer) {
  const noticeDismissed = answer === 'yes' && profile.aldh2Flushing !== 'yes'
    ? false
    : profile.aldh2NoticeDismissed;
  return { ...profile, aldh2Flushing: answer, aldh2NoticeDismissed: noticeDismissed };
}
